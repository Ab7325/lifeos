// The habit tracker that came before Life OS: January to May 2026, the daily tickboxes only (weekly and monthly lists left out).
// Read off the old sheets' own checkbox shapes, and each month's total matches the total printed on its sheet
// (333, 148, 242, 135, 224). Every row was on the list every day, so there are no grey cells: '1' ticked, '0' not.
// Seeded into the months Life OS has no record of (seedLegacyMonths in monthSnapshot.ts); a month it already sealed is left alone.
import type { MonthSnapshot } from './monthSnapshot'


type Row = [id: string, name: string, emoji: string, days: string]

const month = (ym: string, frozenAt: string, rows: Row[]): MonthSnapshot => ({
  ym,
  frozenAt,
  habits: rows.map(([id, name, emoji]) => ({ id, name, emoji, tier: 'standard' as const })),
  cells: Object.fromEntries(rows.map(([id, , , days]) => [id, days])),
})

